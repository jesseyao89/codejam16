// SEVERITY COLORS
// Critical = Red
// High = Golden Orange
// Medium = Yellow
// Low = Green

const severityColors: Record<
  Severity,
  { background: string; text: string }
> = {
  Critical: {
    background: '#FDE7E7',
    text: '#B42318',
  },
  High: {
    background: '#FFF0CC',
    text: '#B86B00',
  },
  Medium: {
    background: '#FFF8C5',
    text: '#806000',
  },
  Low: {
    background: '#DCFCE7',
    text: '#166534',
  },
}

export default function AIReview() {
  const [selectedSeverity, setSelectedSeverity] = useState<
    Severity | 'All'
  >('All')

  const filteredFindings = initialFindings.filter(
    (finding) =>
      selectedSeverity === 'All' ||
      finding.severity === selectedSeverity
  )

  const criticalCount = initialFindings.filter(
    (finding) => finding.severity === 'Critical'
  ).length

  const highCount = initialFindings.filter(
    (finding) => finding.severity === 'High'
  ).length

  return (
    <Box>
      {/* HEADER */}
      <Card
        sx={{
          backgroundColor: '#404D73',
          color: '#FFFFFF',
          mb: 4,
          borderRadius: 3,
        }}
      >
        <CardContent sx={{ p: 4 }}>
          <Stack
            direction="row"
            spacing={2}
            sx={{ alignItems: 'center' }}
          >
            <AutoAwesomeIcon sx={{ fontSize: 36 }} />

            <Box>
              <Typography variant="h5" sx={{ fontWeight: 700 }}>
                AI Risk Intelligence
              </Typography>

              <Typography sx={{ color: '#E0E5F0', mt: 0.5 }}>
                Automated invoice validation and anomaly detection
              </Typography>
            </Box>
          </Stack>
        </CardContent>
      </Card>

      {/* DEMO NOTICE */}
      <Alert severity="info" sx={{ mb: 4 }}>
        Demo mode: These findings are illustrative and are not
        generated by an AI model. No live invoice analysis has
        been performed.
      </Alert>

      {/* SUMMARY CARDS */}
      <Stack
        direction={{ xs: 'column', md: 'row' }}
        spacing={3}
        sx={{ mb: 4 }}
      >
        {[
          {
            label: 'Invoices Analyzed',
            value: 4,
            color: '#404D73',
          },
          {
            label: 'Critical Risks',
            value: criticalCount,
            color: severityColors.Critical.text,
          },
          {
            label: 'High Risks',
            value: highCount,
            color: severityColors.High.text,
          },
          {
            label: 'Total Findings',
            value: initialFindings.length,
            color: '#263451',
          },
        ].map((item) => (
          <Card key={item.label} sx={{ flex: 1 }}>
            <CardContent sx={{ p: 3 }}>
              <Typography color="text.secondary" variant="body2">
                {item.label}
              </Typography>

              <Typography
                variant="h4"
                sx={{
                  fontWeight: 800,
                  color: item.color,
                  mt: 1,
                }}
              >
                {item.value}
              </Typography>
            </CardContent>
          </Card>
        ))}
      </Stack>

      {/* FILTERS */}
      <Stack
        direction="row"
        spacing={1}
        sx={{ mb: 3, flexWrap: 'wrap', gap: 1 }}
      >
        {(['All', 'Critical', 'High', 'Medium', 'Low'] as const).map(
          (severity) => (
            <Button
              key={severity}
              variant={
                selectedSeverity === severity
                  ? 'contained'
                  : 'outlined'
              }
              onClick={() => setSelectedSeverity(severity)}
              sx={{
                textTransform: 'none',
                fontWeight: 600,
                borderColor: '#B7C0D4',
                ...(selectedSeverity === severity
                  ? {
                      backgroundColor: '#404D73',
                      color: '#FFFFFF',
                    }
                  : {
                      color: '#404D73',
                    }),
              }}
            >
              {severity === 'All' ? 'All Findings' : severity}
            </Button>
          )
        )}
      </Stack>

      {/* RISK FINDINGS */}
      <Stack spacing={3}>
        {filteredFindings.map((finding) => (
          <Card
            key={finding.id}
            sx={{
              border: '1px solid #E5E7EB',
              borderLeft: `5px solid ${
                severityColors[finding.severity].text
              }`,
              boxShadow: '0 3px 12px rgba(0,0,0,0.04)',
            }}
          >
            <CardContent sx={{ p: 3 }}>
              <Stack
                direction={{ xs: 'column', sm: 'row' }}
                sx={{
                  justifyContent: 'space-between',
                  alignItems: {
                    xs: 'flex-start',
                    sm: 'center',
                  },
                  gap: 2,
                }}
              >
                <Stack
                  direction="row"
                  spacing={2}
                  sx={{ alignItems: 'center' }}
                >
                  {finding.severity === 'Critical' ? (
                    <ErrorOutlineIcon
                      sx={{
                        color: severityColors.Critical.text,
                        fontSize: 30,
                      }}
                    />
                  ) : finding.severity === 'High' ? (
                    <WarningAmberIcon
                      sx={{
                        color: severityColors.High.text,
                        fontSize: 30,
                      }}
                    />
                  ) : finding.severity === 'Medium' ? (
                    <WarningAmberIcon
                      sx={{
                        color: severityColors.Medium.text,
                        fontSize: 30,
                      }}
                    />
                  ) : (
                    <CheckCircleOutlineIcon
                      sx={{
                        color: severityColors.Low.text,
                        fontSize: 30,
                      }}
                    />
                  )}

                  <Box>
                    <Typography
                      variant="h6"
                      sx={{
                        fontWeight: 700,
                        color: '#263451',
                      }}
                    >
                      {finding.title}
                    </Typography>

                    <Typography
                      variant="body2"
                      color="text.secondary"
                    >
                      {finding.invoiceId} · {finding.vendor}
                    </Typography>
                  </Box>
                </Stack>

                <Stack
                  direction="row"
                  spacing={1}
                  sx={{ alignItems: 'center' }}
                >
                  <Chip
                    label={finding.severity}
                    sx={{
                      fontWeight: 700,
                      backgroundColor:
                        severityColors[finding.severity].background,
                      color:
                        severityColors[finding.severity].text,
                    }}
                  />

                  <Chip
                    label={`Risk ${finding.riskScore}/100`}
                    variant="outlined"
                    sx={{ fontWeight: 700 }}
                  />
                </Stack>
              </Stack>

              <Divider sx={{ my: 2.5 }} />

              <Stack spacing={2}>
                <Box>
                  <Typography
                    variant="caption"
                    sx={{
                      fontWeight: 700,
                      color: '#667085',
                    }}
                  >
                    DETECTION DETAILS
                  </Typography>

                  <Typography sx={{ mt: 0.5, color: '#263451' }}>
                    {finding.description}
                  </Typography>
                </Box>

                <Box
                  sx={{
                    p: 2,
                    backgroundColor: '#F4F6FA',
                    borderRadius: 2,
                  }}
                >
                  <Typography
                    variant="caption"
                    sx={{
                      fontWeight: 700,
                      color: '#404D73',
                    }}
                  >
                    RECOMMENDED ACTION
                  </Typography>

                  <Typography
                    variant="body2"
                    sx={{
                      mt: 0.5,
                      color: '#263451',
                    }}
                  >
                    {finding.recommendation}
                  </Typography>
                </Box>

                <Stack
                  direction="row"
                  spacing={1}
                  sx={{
                    alignItems: 'center',
                    justifyContent: 'space-between',
                  }}
                >
                  <Chip
                    icon={<ReceiptLongIcon />}
                    label={finding.category}
                    size="small"
                    variant="outlined"
                  />

                  <Typography
                    variant="body2"
                    sx={{
                      fontWeight: 700,
                      color: '#263451',
                    }}
                  >
                    {finding.amount}
                  </Typography>
                </Stack>
              </Stack>
            </CardContent>
          </Card>
        ))}
      </Stack>

      {/* EMPTY STATE */}
      {filteredFindings.length === 0 && (
        <Card sx={{ p: 5, textAlign: 'center' }}>
          <Typography color="text.secondary">
            No findings match this filter.
          </Typography>
        </Card>
      )}
    </Box>
  )
}