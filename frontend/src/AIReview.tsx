import { useState } from 'react'

import {
  Alert,
  Box,
  Button,
  Card,
  CardContent,
  Chip,
  Divider,
  Stack,
  Typography,
} from '@mui/material'

import AutoAwesomeIcon from '@mui/icons-material/AutoAwesome'
